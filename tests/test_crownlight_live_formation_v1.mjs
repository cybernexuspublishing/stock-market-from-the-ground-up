import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {webcrypto} from 'node:crypto';
import vm from 'node:vm';
import {mintLiveTicket,verifyLiveTicket,readUpgradeTicket} from '../functions/_lib/crownlight-live-auth-v1.js';
import {onRequest as ticketEndpoint} from '../functions/api/live-market-ticket.js';
import {onRequest as streamEndpoint} from '../functions/api/live-market-stream.js';
if(!globalThis.crypto)globalThis.crypto=webcrypto;
const env={MARKET_DATA_ENCRYPTION_KEY:'fixture-private-key-for-test-only-never-production'};
const userId='11111111-1111-4111-8111-111111111111';
const ticket=await mintLiveTicket(env,{userId,symbol:'AAPL'},Date.UTC(2026,9,28,13));
assert.deepEqual(await verifyLiveTicket(env,ticket,Date.UTC(2026,9,28,13)),{userId,symbol:'AAPL'});
await assert.rejects(verifyLiveTicket(env,ticket+'x',Date.UTC(2026,9,28,13)),/Invalid or expired/);
await assert.rejects(verifyLiveTicket(env,ticket,Date.UTC(2026,9,28,13)+21_000),/Invalid or expired/);
await assert.rejects(mintLiveTicket(env,{userId,symbol:'../secret'},Date.now()),/Invalid or expired/);
assert.equal(readUpgradeTicket(new Request('https://example.test/api/live-market-stream',{headers:{
 'Sec-WebSocket-Protocol':'crownlight-v1, ticket.'+ticket}})),ticket);
assert.throws(()=>readUpgradeTicket(new Request('https://example.test/api/live-market-stream',{headers:{
 'Sec-WebSocket-Protocol':'crownlight-v1, ticket.fake, ticket.extra'}})),/Invalid or expired/);
const unauthorized=await ticketEndpoint({env,request:new Request('https://example.test/api/live-market-ticket',{method:'GET'})});
assert.equal(unauthorized.status,405);
const noWebSocket=await streamEndpoint({env,request:new Request('https://example.test/api/live-market-stream')});
assert.equal(noWebSocket.status,426);
const source=readFileSync('assets/js/crownlight-live-aggregator-v1.js','utf8');
const sandbox={globalThis:{},console,Date,Number,Math};vm.createContext(sandbox);
vm.runInContext(source,sandbox);
const agg=sandbox.globalThis.CrownlightLiveAggregator.create('AAPL');
const trade=(i,p,s,t)=>({T:'t',S:'AAPL',i,p,s,t});
assert.equal(agg.ingest(trade(1,100,10,'2026-10-22T13:30:02Z')).accepted,true);
assert.equal(agg.ingest(trade(2,101,20,'2026-10-22T13:30:12Z')).accepted,true);
let active=agg.active;
assert.equal(active.open,100);assert.equal(active.high,101);assert.equal(active.low,100);
assert.equal(active.close,101);assert.equal(active.volume,30);assert.equal(active.tradeCount,2);
assert(Math.abs(active.providerVwap-(3020/30))<0.0000001,'Volume-weighted streamed trade price');
assert.equal(agg.ingest(trade(2,101,20,'2026-10-22T13:30:12Z')).reason,'duplicate');
assert.equal(agg.ingest(trade(3,99,10,'2026-10-22T13:29:59Z')).reason,'late');
let next=agg.ingest(trade(4,102,15,'2026-10-22T13:31:02Z'));
assert(next.finalized&&!next.finalized.forming);
assert.equal(agg.snapshot().length,2);
assert.equal(agg.finalizeAt(Date.parse('2026-10-22T13:32:02Z')).forming,false);
assert.equal(agg.snapshot().length,2,'Must not backfill gaps with invented candles');
assert.equal(agg.ingest({T:'b',S:'AAPL',t:'2026-10-22T13:33:00Z',p:10,s:10}).accepted,false);
