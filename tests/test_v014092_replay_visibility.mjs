import assert from 'node:assert/strict';
import {validateReplayBars,visibleReplayBars,commitmentBoundReplay} from '../functions/_lib/replay-visibility-v01492.js';
const data=Array.from({length:6},(_,i)=>({timestamp:new Date(Date.UTC(2024,3,26,13,30+i*5)).toISOString(),open:100+i,high:101+i,low:99+i,close:100+i,volume:1000+i}));
const valid=validateReplayBars(data);
assert.equal(valid.length,6);
assert.equal(visibleReplayBars(data,0).bars.length,1);
assert.equal(visibleReplayBars(data,2).bars.length,3);
assert.equal(visibleReplayBars(data,2,{lag:1}).bars.length,2);
assert.equal(visibleReplayBars(data,1,{lag:3}).bars.length,0);
assert.deepEqual(visibleReplayBars(data,2).bars.map(x=>x.close),[100,101,102]);
assert.equal(visibleReplayBars(data,2).bars.some(x=>x.close===105),false,'future close is inaccessible');
assert.throws(()=>visibleReplayBars(data,6),/outside/);
assert.throws(()=>visibleReplayBars(data,-1),/cursor/);
assert.throws(()=>visibleReplayBars(data,1.5),/cursor/);
assert.throws(()=>visibleReplayBars(data,2,{lag:-1}),/cursor/);
assert.throws(()=>validateReplayBars([]),/Dataset/);
assert.throws(()=>validateReplayBars([...data,...data]),/chronological/);
assert.throws(()=>validateReplayBars([data[0],{...data[0],timestamp:data[0].timestamp}]),/chronological/);
assert.throws(()=>validateReplayBars([{...data[0],high:98}]),/OHLCV/);
assert.throws(()=>validateReplayBars([{...data[0],volume:-1}]),/OHLCV/);
assert.throws(()=>validateReplayBars([{...data[0],close:NaN}]),/Invalid close/);
assert.throws(()=>commitmentBoundReplay(data,2,null),/locked/);
assert.throws(()=>commitmentBoundReplay(data,2,{locked:false,authorizedCursor:2}),/locked/);
assert.throws(()=>commitmentBoundReplay(data,2,{locked:true,authorizedCursor:3}),/locked/);
assert.equal(commitmentBoundReplay(data,2,{locked:true,authorizedCursor:2}).bars.length,3);
console.log('PASS v92 deterministic OHLCV validation, exclusive future-bar visibility, server cursor and decision commitment gates');
