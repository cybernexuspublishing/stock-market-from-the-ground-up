/* v0.14.0.21 isolated API test: mock identity/RPC, no production data. */
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const file=readFileSync('functions/api/commons-subscriptions-v01421.js','utf8');
const {onRequest}=await import('data:text/javascript;base64,'+Buffer.from(file).toString('base64'));
const env={SUPABASE_URL:'https://test.supabase.co',SUPABASE_PUBLISHABLE_KEY:'public-test-key'};
const response=(body,code=200)=>new Response(JSON.stringify(body),{status:code,headers:{'content-type':'application/json'}});
const checks=[];
function mock(fn){globalThis.fetch=async(url,opts)=>{const result=fn(String(url),opts);checks.push({url:String(url),method:opts.method||'GET',authorization:opts.headers?.authorization,body:opts.body});return result}};
const request=(method,topic='93',body=undefined,token='jwt-token')=>new Request(`https://example.com/api/commons-subscriptions-v01421?topicId=${topic}`,{method,headers:token?{authorization:'Bearer '+token,'content-type':'application/json'}:{'content-type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
const call=async req=>{let r=await onRequest({request:req,env});return [r.status,await r.json(),r.headers.get('cache-control')]};
let [status]=await call(request('GET','93',undefined,''));assert.equal(status,401);
[status]=await call(request('GET','-93'));assert.equal(status,400);
[status]=await call(request('GET','0'));assert.equal(status,400);
[status]=await call(request('GET','9%20OR%201'));assert.equal(status,400);
[status]=await call(request('POST','93',{subscribe:'true'}));assert.equal(status,400);
[status]=await call(request('POST','93',{subscribe:true,userId:'other'}));assert.equal(status,400);
[status]=await call(request('PUT','93'));assert.equal(status,405);
mock((url)=>url.includes('/auth/v1/user')?response({id:'caller-uuid'}):response({available:true,subscribed:false}));
let out=await call(request('GET'));
assert.equal(out[0],200);assert.deepEqual([out[1].available,out[1].subscribed],[true,false]);assert.match(out[2],/no-store/);
assert.equal(checks.at(-1).method,'POST');assert.equal(checks.at(-1).body,JSON.stringify({p_topic_id:93}));
checks.length=0;
mock((url,opts)=>url.includes('/auth/v1/user')?response({id:'caller-uuid'}):response({available:true,subscribed:JSON.parse(opts.body).p_subscribe}));
out=await call(request('POST','93',{subscribe:true}));assert.deepEqual([out[0],out[1].subscribed],[200,true]);
assert.equal(checks.at(-1).body,JSON.stringify({p_topic_id:93,p_subscribe:true}));
assert.equal(checks.at(-1).authorization,'Bearer jwt-token');
assert.ok(checks.every(c=>c.authorization!=='Bearer undefined'));
out=await call(request('POST','93',{subscribe:false}));assert.deepEqual([out[0],out[1].subscribed],[200,false]);
checks.length=0;
mock((url)=>url.includes('/auth/v1/user')?response({id:'caller-uuid'}):response({available:false,subscribed:false}));
out=await call(request('GET'));assert.equal(out[1].available,false);
mock((url)=>url.includes('/auth/v1/user')?response({id:'caller-uuid'}):response({message:'RPC missing'},404));
out=await call(request('GET'));assert.equal(out[0],503);
mock(()=>response({message:'Unauthorized'},401));
out=await call(request('GET'));assert.equal(out[0],401);
console.log('v0.14.0.21 API authorization/validation/contract tests: PASS');
