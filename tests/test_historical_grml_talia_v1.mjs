import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const source=readFileSync('assets/js/historical-grml-talia-v1.js','utf8');
const context={window:{},Date,Intl,console};
vm.runInNewContext(source,context,{filename:'historical-grml-talia-v1.js'});
const lesson=context.window.CrownlightGrmlTalia;
assert(lesson,'Talia lesson must register after authenticated replay HTML loads');
assert.equal(lesson.stageCount,8);
assert.equal(lesson.stageAt(0),null);
const checkpoints=[1,3,5,10,15,20,25,30];
for(let i=1;i<=30;i++){
 const stage=lesson.stageAt(i);
 const latest=checkpoints.filter(n=>n<=i).at(-1);
 assert.equal(stage.at,latest,'Stage may not advance earlier than the protected server cursor');
 assert.equal(lesson.isCheckpoint(i),checkpoints.includes(i)&&i>1);
 assert.equal(stage.options.length,3,'Every stage requires three ungraded teaching choices');
 assert(stage.correct>=0&&stage.correct<=2);
 assert(!stage.options[stage.correct].includes('guarantee'),'Correct answer must not promise future prices');
 assert(stage.transfer.length>20,'Ungraded retry/transfer instruction required');
 assert(stage.why.length>20&&stage.retry.length>20,'Feedback and retries must be instructional');
}
const latest={ms:Date.parse('2026-09-21T13:30:00Z'),o:4.2,h:4.5,l:4.1,c:4.4,v:120};
let current=lesson.describe({revealed:1,completed:[latest],frame:1});
assert.match(current.evidence,/4\.2000/);
assert.match(current.evidence,/120 shares/);
assert(!current.evidence.includes('9.9999'),'Unknown future price must not appear');
current=lesson.describe({revealed:3,completed:[],frame:5});
assert.match(current.evidence,/No completed 5-minute candle/);
assert.equal(current.id,'structure');
const future={...latest,c:9.9999,h:9.9999,ms:Date.parse('2026-09-21T13:31:00Z')};
current=lesson.describe({revealed:2,completed:[latest],frame:1});
assert(!current.evidence.includes('9.9999'),'Only supplied already-completed observations may be described');
assert.equal(lesson.describe({revealed:3,completed:[latest,future],frame:1}).sourceCount,3);
assert.equal(lesson.stageAt(14).id,'levels');
assert.equal(lesson.stageAt(15).id,'timeframes');
assert.equal(lesson.stageAt(29).id,'no-trade');
assert.equal(lesson.stageAt(30).id,'review');
assert.match(source,/Ungraded|ungraded/);
const classroom=readFileSync('assets/js/historical-replay-classroom-v1.js','utf8');
const html=readFileSync('verified-replay.html','utf8');
assert(html.indexOf('historical-grml-talia-v1.js')<html.indexOf('historical-replay-classroom-v1.js'),'Lesson must load before classroom');
assert.match(classroom,/dataset\?\.code==='HR_GRML_20260921'/);
assert.match(classroom,/grmlAnswers\.clear\(\)/,'Account/sign-out reset clears local learning replies');
assert.match(classroom,/CrownlightGrmlTalia\?\.isCheckpoint/,'Protected progression controls stage pauses');
assert.match(classroom,/groundup:replay-observation/);
assert.match(classroom,/renderGrmlLesson\(grouped\)/);
assert.match(classroom,/No completed/);
console.log('PASS GRML coaching: eight evidence-timed teach-demonstrate-check-feedback-transfer stages, no future values, ungraded retries, session cleanup and integration.');
