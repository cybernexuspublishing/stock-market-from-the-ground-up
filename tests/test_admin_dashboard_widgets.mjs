import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {recordCount,dashboardCharts} from '../assets/js/admin-dashboard-widgets-core.mjs';
assert.equal(recordCount(0),0);
for(const value of [undefined,null,-1,'25',Infinity,NaN,1.5])assert.equal(recordCount(value),null,'Unknown or invalid counts must not become zero or plotted data');
const charts=dashboardCharts({orders:20,subscriptions:5,library:0,publishedContent:10,catalogProducts:null});
assert.equal(charts[0].rows[0].width,100);
assert.equal(charts[0].rows[1].width,25);
assert.equal(charts[1].rows[0].width,0);
assert.equal(charts[1].rows[2].count,null);
for(const group of dashboardCharts({orders:0,subscriptions:0}))for(const row of group.rows)assert(Number.isFinite(row.width)&&row.width>=0&&row.width<=100);
const ui=readFileSync('assets/js/admin-dashboard-widgets.js','utf8');
assert(!/\bfetch\s*\(|localStorage|sessionStorage|\.innerHTML\s*=|setInterval/.test(ui),'Presentation must reuse summary data without new reads, writes or unsafe HTML');
assert.match(ui,/SHOWCASE · SYNTHETIC DATA/);
assert.match(ui,/GroundUpAdminSummarySnapshot/,'Handle module-load race without a second API call');
assert.match(ui,/dataset.ccMetric=target/,'Use existing permission-aware navigation');
assert.match(ui,/setAttribute\('role','img'\)/);
assert.match(ui,/setAttribute\('aria-label'/);
assert.match(readFileSync('assets/js/admin.js','utf8'),/showcase:j.showcase===true/);
console.log('PASS dashboard chart scale, zero/missing values, Showcase label, accessible summaries and canonical navigation; no new APIs or fabricated trends.');
