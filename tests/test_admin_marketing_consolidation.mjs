import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const read=p=>readFileSync(p,'utf8');
const html=read('admin-advertising.html');
const before=execFileSync('git',['show','HEAD:admin-advertising.html'],{encoding:'utf8'});
const ids=s=>[...s.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]).sort();
assert.deepEqual(ids(html),ids(before),'All existing Ads form/data mount IDs retained exactly');
const workspace=read('assets/js/admin-marketing-workspace.js');
assert.match(workspace,/destinations\[key\]\.append\(section\)/,'Move original connected sections, never clone controls');
assert.match(workspace,/if\(mounted\)/,'Refresh must not duplicate navigation or forms');
assert.match(workspace,/if\(!main\|\|main.hidden\)return/,'Cannot mount before existing Owner authorization succeeds');
assert.doesNotMatch(workspace,/\bfetch\s*\(|localStorage|sessionStorage|\.innerHTML\s*=/,'No parallel backend, token storage or unsafe dynamic HTML');
for(const id of [...workspace.matchAll(/'((?:gu-ad-)[a-z-]+)'/g)].map(x=>x[1]))assert(html.includes('id="'+id+'"'),'Unknown Ads mount '+id);
assert.match(workspace,/not been established/,'Do not claim a connected X account');
assert.match(workspace,/Not implemented in this release/,'Unavailable social workflows must be explicit');
assert.match(workspace,/@SMFGUAcademy/);
const nav=read('assets/js/admin-simple-navigation-v014036.js');
const labels=[...nav.slice(nav.indexOf('const entries=['),nav.indexOf('let initialized')).matchAll(/title:'([^']+)'/g)].map(x=>x[1]);
assert.deepEqual(labels,['Overview','People','Learning','Commerce','Community','Platform']);
assert.match(read('admin.html'),/data-owner-marketing hidden/);
assert.match(read('assets/js/admin.js'),/roles\?\.includes\('OWNER'\)&&ADMIN.ctx.permissions.includes\('ads.view'\)/);
console.log('PASS marketing consolidation: original Ads IDs retained, six-area directory, Owner-gated mount, no new writes/storage, honest social integration status.');
