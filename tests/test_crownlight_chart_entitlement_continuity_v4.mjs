import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {webcrypto} from 'node:crypto';
import {createRequire} from 'node:module';
import {runInNewContext} from 'node:vm';
const require=createRequire(import.meta.url);
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('assets/js/crownlight-sparks-redemption-retry-v1.js');
const uid='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',other='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
const sku='CHART_PROFESSIONAL_DAY';
const m=new Map(),store={getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)};
const vmRoot={crypto:webcrypto,sessionStorage:store,Date,JSON,Map,Error,String,Number,Object};
const run=()=>{runInNewContext(source,vmRoot,{timeout:1000});return vmRoot.CrownlightSparksRetryV1};
let retry=run();
const initial=retry.acquire(uid,sku);
assert.match(initial,/^[a-f0-9-]{36}$/);
assert.equal(retry.acquire(uid,sku),initial,'uncertain HTTP response must reuse same idempotency UUID');
retry=run();
assert.equal(retry.acquire(uid,sku),initial,'reload must not create a second redeemable transaction');
assert.notEqual(retry.acquire(other,sku),initial,'different member must never reuse first member transaction');
assert.notEqual(retry.acquire(uid,'CHART_ADVANCED_DAY'),initial,'different offer must not share receipt');
assert.equal(retry.confirm(uid,sku,'00000000-0000-4000-8000-000000000000'),false);
assert.equal(retry.acquire(uid,sku),initial,'wrong confirmation must preserve pending receipt');
assert.equal(retry.confirm(uid,sku,initial),true);
assert.notEqual(retry.acquire(uid,sku),initial,'confirmed entitlement starts a new future purchase intent');
assert.throws(()=>retry.acquire(uid,'CHART_PROFESSIONAL_LIFETIME'),/Invalid chart purchase identity/);
assert.throws(()=>retry.acquire('not-a-member',sku),/Invalid chart purchase identity/);
const tier=read('assets/js/crownlight-chart-tiers-v1.js');
const handler=tier.slice(tier.indexOf('async function redeemSparkOffer('),tier.indexOf('function explainLockedTier()'));
assert.match(handler,/retry\.acquire\(memberId,offer\.sku\)/);
assert.match(handler,/requestId:receipt/);
assert.match(handler,/retry\.confirm\(memberId,offer\.sku,receipt\)/);
assert.ok(handler.indexOf('state.allowed.includes(offer.tier)')<handler.lastIndexOf('retry.confirm('));
assert.doesNotMatch(handler,/requestId:\s*crypto\.randomUUID\(\)/);
const html=read('simulator.html');
assert.ok(html.indexOf('crownlight-sparks-redemption-retry-v1.js')<
 html.indexOf('crownlight-chart-tiers-v1.js'));
const workspace=read('functions/api/chart-workspace.js');
assert.match(workspace,/gu_crownlight_chart_workspace_save_v4/);
assert.match(workspace,/p_max_tier:e\.tier/);
assert.match(workspace,/PREMIUM_WORKSPACE_PRESERVED/);
const sql=read('supabase/migrations/20261030_chart_workspace_preserve_premium_v4.sql');
assert.match(sql,/stored_rank>permitted_rank/);
assert.match(sql,/v_previous|previous\.updated_at/);
assert.match(sql,/REVOKE ALL ON FUNCTION public\.gu_crownlight_chart_workspace_save_v4/);
assert.match(sql,/GRANT EXECUTE ON FUNCTION public\.gu_crownlight_chart_workspace_save_v4/);
assert.doesNotMatch(sql,/UPDATE public\.gu_sparks_|DELETE FROM public\.crownlight_chart_workspaces_v1/);
console.log('PASS Chart Studio: stable Sparks retry per member + offer across reload, no duplicate receipt on uncertain payment, protected premium workspace with server-verified tier, source and credential boundaries');
