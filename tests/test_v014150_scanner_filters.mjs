import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const code=readFileSync('assets/js/market-research-engine-v014145.js','utf8');
const scope={TextEncoder,Math,Number,String,Array,Object,Set,RegExp,Date};scope.globalThis=scope;
runInNewContext(code,scope);
const S=scope.GroundUpScannerV014145;
const A={symbol:'AAA',price:5,change_pct:12,volume:18000000,rvol:3,float:9000000,spread_pct:1.4,gap_pct:8,market_cap:45000000};
const B={...A,symbol:'BBB',gap_pct:2,market_cap:90000000};
const C={...A,symbol:'CCC',gap_pct:'',market_cap:''};
const f={minPrice:3,maxPrice:10,minGap:5,maxMarketCap:50000000,minDollarVolume:50000000};
const good=S.analyze([A,B,C],f);
assert.deepEqual(Array.from(good.rows,x=>x.symbol),['AAA']);
assert.equal(good.rejections.failedThreshold,1);
assert.equal(good.rejections.missingMetric,1,'Optional required metric must fail closed when filter enabled');
assert.equal(good.rows[0].dollarVolume,90000000);
assert.equal(good.rows[0].marketCap,45000000);
assert.equal(good.rows[0].gap,8);
assert.equal(S.analyze([C]).matched,1,'Missing optional fields do not block existing default scan');
assert.equal(S.analyze([A],{minPrice:6}).matched,0);
assert.equal(S.analyze([A],{minDollarVolume:100000000}).matched,0);
assert.throws(()=>S.filters({minPrice:-1}),/Invalid filter/);
assert.throws(()=>S.filters({maxMarketCap:'Infinity'}),/Invalid filter/);
assert.throws(()=>S.filters({unknownCondition:1}),/Unsupported scanner filter/);
assert.throws(()=>S.filters({minPrice:11,maxPrice:10}),/Minimum price/);
assert.equal(S.analyze([{...A,vwap:4.5}],{minVwapDistancePct:10}).matched,1);
assert.equal(S.analyze([{...A,vwap:4.5}],{minVwapDistancePct:12}).matched,0);
assert.equal(S.analyze([A],{minVwapDistancePct:1}).rejections.missingMetric,1);
const ui=readFileSync('assets/js/advanced-tools.js','utf8');
for(const id of ['u-minprice','u-mingap','u-maxmcap','u-mindollarvol','u-minvwap'])
 assert(ui.includes(id),'Snapshot scanner filter UI missing: '+id);
assert(ui.includes('engine.analyze(rows,getFilters())'),'Actual snapshot filter integration');
assert.match(ui,/sourceNote:label,asOf:at,verified:false/);
console.log('PASS D10 optional price/gap/cap/dollar-volume proxy filters, missing metrics and unverified rights labeling');
