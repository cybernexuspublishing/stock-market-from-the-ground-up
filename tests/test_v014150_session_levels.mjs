import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const source=readFileSync('assets/js/market-analysis-engine-v014146.js','utf8');
const scope={TextEncoder,Math,Number,String,Array,Object,Set,Map,RegExp,Date,Intl};scope.globalThis=scope;
runInNewContext(source,scope);
const A=scope.GroundUpMarketAnalysisV014146;
const make=(at,high,low=high-1)=>({timestamp:Date.parse(at),high,low,open:low+0.5,close:low+0.5,volume:100});
const prior1=make('2026-10-21T13:30:00Z',15);
const prior2=make('2026-10-21T19:00:00Z',16);
const pre1=make('2026-10-22T08:00:00Z',10);
const pre2=make('2026-10-22T12:00:00Z',13);
const today=make('2026-10-22T13:30:00Z',12);
const all=A.sessionReferenceSeries([prior1,prior2,pre1,pre2,today]);
assert.equal(all.snapshots.length,5);
assert.equal(all.snapshots[0].priorObservedRegularHigh,null);
assert.equal(all.snapshots[2].priorObservedRegularHigh,16);
assert.equal(all.snapshots[2].priorObservedRegularDate,'2026-10-21');
assert.equal(all.snapshots[3].observedPmh,13);
assert.equal(all.snapshots[3].observedHod,13);
assert.equal(all.snapshots[4].observedHod,13);
assert.equal(all.snapshots[4].observedPmh,13);
assert.equal(all.snapshots[4].observedLod,9);
assert.equal(all.snapshots[4].verifiedComplete,false);
assert(A.sessionReferenceSeries([prior1,prior2,pre1]).snapshots[2].observedHod===10,
 'future premarket high must never appear in an earlier snapshot');
assert.throws(()=>A.sessionReferenceSeries([prior2,prior1]),/chronological/);
assert.throws(()=>A.sessionReferenceSeries([prior1,prior1]),/chronological/);
assert.equal(A.sessionReferenceSeries([make('2026-10-22T02:00:00Z',8)]).excluded,1);
const ui=readFileSync('assets/js/market-analysis-workbenches-v014146.js','utf8');
assert(ui.includes('A.sessionReferenceSeries(rows)'));
assert(ui.includes('session completeness and actual PDH/PDL require independent verification'));
console.log('PASS D10 observed-only ET HOD/LOD/PMH/PML, prior-session tentative levels, chronology and no-lookahead');
