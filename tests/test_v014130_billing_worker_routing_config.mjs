import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join,dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const configPath=join(root,'workers/wrangler.billing-scheduler.jsonc');
const raw=readFileSync(configPath,'utf8').replace(/^\s*\/\/.*$/gm,'');
const c=JSON.parse(raw);
assert.equal(c.name,'ground-up-billing-scheduler','Must update exact existing Worker');
assert.equal(c.main,'./billing-reconcile-stripe-only-v014129.js','Must use v129 Stripe-only entrypoint');
assert.equal(c.compatibility_date,'2026-10-20');
assert(c.compatibility_flags.includes('global_fetch_strictly_public'));
assert.equal(c.keep_vars,true,'Must preserve existing dashboard env vars');
assert.equal(c.workers_dev,true,'Preserve existing public Worker route');
assert.equal(c.observability?.enabled,true);
assert.deepEqual(c.triggers?.crons,['0 12 * * *'],'Do not retain every-minute trigger');
assert.equal(c.vars,undefined,'No credentials or duplicate origin in source control');
assert.equal(c.account_id,undefined,'Do not hard-code an account');
assert.equal(c.route,undefined,'Must not take over Pages routing');
assert.equal(c.routes,undefined,'Must not take over Pages routing');
assert(!JSON.stringify(c).match(/(?:sk_live_|whsec_|GU_BILLING_TASK_SECRET|sb_secret_)/));
const mainPath=resolve(dirname(configPath),c.main);
const js=readFileSync(mainPath,'utf8');
assert(js.includes('/api/internal-billing-reconcile-v014124'));
assert(!js.includes("'/api/internal-billing-notices-v014123'"));
assert(js.includes('async scheduled('));
assert(js.includes('async fetch('));
console.log('PASS v130 Wrangler config: existing Worker, public fetch flag, dashboard variables preserved, daily-only Cron and v129 code');
