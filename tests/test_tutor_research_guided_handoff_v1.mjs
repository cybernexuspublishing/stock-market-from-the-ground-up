import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {answerFromGuide} from '../functions/_lib/original-competency-tutor-v014100.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const base=JSON.parse(read('data/competency-study-guides-v01499.json'));
const lessons=JSON.parse(read('data/tutor-guided-practice-v1.json')).modules;
assert.equal(base.guides.length,30);
assert.equal(lessons.length,134);
assert.equal(new Set(lessons.map(x=>x.guideCode)).size,134);
const expanded=answerFromGuide(base.guides[0],'explain','','Teach this in more depth: structural chart reading');
for(const k of ['First principle:','Observe and define inputs:','Common live-trading error:','Original ungraded check:','not an official score'])assert(expanded.includes(k),k);
assert(!answerFromGuide(base.guides[0],'explain','').includes('Source-only deeper teaching'));
const context={window:{},document:{readyState:'loading',addEventListener(){}},console,Date,Number,Math,Array,Object,Set,String,JSON,Intl};
context.globalThis=context.window;
vm.runInNewContext(read('assets/js/crownlight-indicator-math-v2.js'),context);
vm.runInNewContext(read('assets/js/tutor-guided-practice-v1.js'),context);
const gp=context.window.TaliaGuidedPracticeV1;
for(const q of ['STUDY_SMA','simple moving average','IND-01'])assert.equal(gp.findLesson(q,lessons).id,'IND-01');
assert.equal(gp.findLesson('REPLAY_EVENT_CREX_2020_04_28',lessons).id,'EVENT-01');
assert.equal(gp.findLesson('not an approved real trade',lessons),null);
assert.equal(gp.findLesson('STUDY_SMA',[]),null);
assert.equal(gp.openLesson('not an approved real trade'),false);
const client=read('assets/js/market-tutor.js'),server=read('functions/api/market-tutor-v01492.js');
for(const x of ['talia-guided-practice-ready','Teach this in more depth (source-only)','consent.checked=false','sourceCodes:'])assert(client.includes(x),x);
assert(server.includes("reason:'source_only_deep_teaching'"));
assert(server.includes('answerFromGuide(guide,mode,answer,q)'));
console.log('PASS: 134 exact source-to-lesson routes, deeper source-only teaching, no model auto-consent and 30 competencies unchanged.');
