import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const scope={TextEncoder,Math,Number,String,Array,Object,Set,RegExp,Date};scope.globalThis=scope;
runInNewContext(readFileSync('assets/js/market-research-engine-v014145.js','utf8'),scope);
const M=scope.GroundUpScannerV014145;
assert.equal(M.sma([1,2,3,4,5],3).value,4);
assert.equal(M.sma([1,2],3),null);
assert.equal(M.sma([1,0,3,4],3),null);
const bars=Array.from({length:16},(_,i)=>({high:12,low:10,close:11,open:11,volume:100+i}));
assert.equal(M.wilderAtr(bars,14).value,2);
assert.equal(M.wilderAtr(bars.slice(0,14),14),null,'ATR from prior closes requires period+1 bars');
const jumped=bars.map(x=>({...x}));jumped[15]={high:17,low:15,close:16};
const atr=M.wilderAtr(jumped,14);
assert(Math.abs(atr.value-(2*13+6)/14)<1e-12,'Wilder ATR recursive update and gap true range');
assert.match(atr.seed,/bar 2/);
assert.equal(M.wilderAtr([{...bars[0],high:9},...bars.slice(1)],14),null);
assert.equal(M.wilderAtr([...bars.slice(0,15),{...bars[15],close:NaN}],14),null);
assert.match(M.wilderAtr(bars,14).label,/NOT VERIFIED/);
const ui=readFileSync('assets/js/market-analysis-workbenches-v014146.js','utf8');
assert(ui.includes('M?.sma(closes,20)'));
assert(ui.includes('M?.wilderAtr(rows,14)'));
