import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
execFileSync(process.execPath,['scripts/curriculum-acceptance-evidence.mjs'],{stdio:'pipe'});
const ledger=JSON.parse(readFileSync('artifacts/curriculum-acceptance-v014150.json','utf8'));
const choices=JSON.parse(readFileSync('docs/curriculum-acceptance-decisions-v014150.json','utf8'));
assert.equal(ledger.labCount,419);
assert.equal(ledger.bootcampDays,30);
assert.equal(ledger.competencies,30);
assert.equal(ledger.labs.length,419);
assert.equal(ledger.bootcamp.length,30);
assert.equal(new Set(ledger.labs.map(l=>l.id)).size,419);
assert.deepEqual(ledger.bootcamp.map(d=>d.day),Array.from({length:30},(_,i)=>i+1));
assert.equal(ledger.groups.FOUNDATION_BOOK_1,15);
assert.equal(ledger.groups.FOUNDATION_BOOK_2,46);
assert.equal(ledger.groups.FOUNDATION_BOOK_3,33);
assert.equal(ledger.groups.DAY_TRADING_BOOK_1,150);
assert.equal(ledger.groups.READING_THE_TAPE,75);
assert.equal(ledger.groups.SITE_EXCLUSIVE,100);
assert(ledger.acceptedLabs>=0&&ledger.acceptedLabs<=419);
assert(ledger.acceptedDays>=0&&ledger.acceptedDays<=30);
assert.equal(ledger.independentProductionAcceptanceVerified,false);
assert(ledger.labs.every(row=>row.title&&row.mappedCompetencies&&row.criterionStatus.production));
assert(ledger.bootcamp.every(row=>row.title&&row.mappedCompetencies&&row.criterionStatus.production));
if(!Object.keys(choices.labDecisions).length)assert.equal(ledger.acceptedLabs,0);
if(!Object.keys(choices.bootcampDecisions).length)assert.equal(ledger.acceptedDays,0);
assert(existsSync('artifacts/curriculum-acceptance-v014150.csv'));
console.log('PASS D11-14/D18 ledger: 419 unique Labs, 30 Bootcamp days, 30 competencies and no unearned source-to-production promotion');
